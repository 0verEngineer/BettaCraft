/**
 * Shrimp, crayfish and snails of a tank (M14), drawn by the controller's block entity renderer as small 3D models
 * ({@code CritterModelDefinitions}, generated by tools/assetgen/critters.py): each group of a model gets its own tint
 * (variety colour of the shell or body, pale legs and feelers, dark eyes, eggs under the tail of a carrying female),
 * walking legs and swaying feelers. On the glass they lie with the belly against it. The positions glide linearly
 * between two server updates. Also the apple snail clutches (pink) and the shed crayfish shells.
 */
public final class CritterRenderer {
    public static final Map<CritterSpecies.Model, ModelLayerLocation> LAYERS = new EnumMap<>(CritterSpecies.Model.class);
    public static final ModelLayerLocation FROG_LAYER = new ModelLayerLocation(BettaCraft.id("dwarf_clawed_frog"), "main");

    static {
        for (CritterSpecies.Model m : CritterSpecies.Model.values()) {
            LAYERS.put(m, new ModelLayerLocation(BettaCraft.id("critter_" + name(m)), "main"));
        }
    }

    private static final Map<CritterSpecies.Model, ModelPart> MODELS = new EnumMap<>(CritterSpecies.Model.class);
    private static final Map<CritterSpecies.Model, Map<String, ModelPart>> GROUPS = new EnumMap<>(CritterSpecies.Model.class);
    private static final Map<CritterSpecies.Model, Identifier> TEXTURES = new EnumMap<>(CritterSpecies.Model.class);
    private static final String[] GROUP_NAMES = {"body", "legs", "antennae", "eyes", "eggs", "claws", "shell", "foot", "tentacles", "horns"};
    private static final int EYE = 0x161414;

    private CritterRenderer() {}

    public static String name(CritterSpecies.Model m) {
        return switch (m) {
            case SHRIMP -> "shrimp";
            case CRAYFISH -> "crayfish";
            case NERITE -> "nerite";
            case APPLE -> "apple";
            case RAMSHORN -> "ramshorn";
            case BLADDER -> "bladder";
            case TRUMPET -> "trumpet";
            case ASSASSIN -> "assassin";
            case HERMIT -> "hermit"; // M20
            case TURBO -> "turbo";
            case TYLOMELANIA -> "tylomelania"; // M25c
        };
    }

    /** Forgets the baked models (resource reload); they are baked again when drawn. */
    public static void reset() {
        MODELS.clear();
        GROUPS.clear();
    }

    /** Bakes the models (lazily on the first frame after a reload). */
    public static void bake() {
        MODELS.clear();
        GROUPS.clear();
        var set = Minecraft.getInstance().getEntityModels();
        for (CritterSpecies.Model m : CritterSpecies.Model.values()) {
            ModelPart root = set.bakeLayer(LAYERS.get(m));
            MODELS.put(m, root);
            Map<String, ModelPart> g = new HashMap<>();
            for (String n : GROUP_NAMES) if (root.hasChild(n)) g.put(n, root.getChild(n));
            GROUPS.put(m, g);
            TEXTURES.put(m, BettaCraft.id("textures/entity/critters/" + name(m) + ".png"));
        }
    }

    /** Critter update of a tank (network thread hands it over to the client thread). */
    public static void accept(TankCrittersPayload payload) {
        Level level = Minecraft.getInstance().level;
        if (level == null || !level.isLoaded(payload.controller())) return;
        if (!(level.getBlockEntity(payload.controller()) instanceof TankBlockEntity be) || !be.isController() || be.getTank() == null) return;
        TankData t = be.getTank();
        var dec = CritterSync.decode(payload.data(), t.min().getX(), t.min().getY(), t.min().getZ());
        CritterSync.adopt(t.critters(), dec.critters(), level.getGameTime(), TankPlants.SYNC_TICKS);
        t.critters().clear();
        t.critters().addAll(dec.critters());
        t.critterObjects().clear();
        t.critterObjects().addAll(dec.objects());
    }

    // ------------------------------------------------------------------ colours

    public static int bodyColor(Critter k) {
        return look(k).body();
    }

    /** M21.5: the shell colour with the individual look (racer nerites, apple snails) and the lines over it. */
    public static org.overengineer.bettacraft.critters.CritterLooks.Look look(Critter k) {
        int c = CritterGenes.rgb(k.species, k.clientColor, k.clientGrade);
        if (k.species.nerite() || k.species == CritterSpecies.ASSASSIN_SNAIL) c = k.species.wildColor();
        return org.overengineer.bettacraft.critters.CritterLooks.of(k.species, k.clientColor, c, k.look);
    }

    /** M21.5: overlays of the shell (thin or wide lines of a racer nerite, the bands of an apple snail). */
    private static final Map<org.overengineer.bettacraft.critters.CritterLooks.Lines, net.minecraft.resources.Identifier> LINES = Map.of(
            org.overengineer.bettacraft.critters.CritterLooks.Lines.FINE, BettaCraft.id("textures/entity/critters/nerite_lines_fine.png"),
            org.overengineer.bettacraft.critters.CritterLooks.Lines.WIDE, BettaCraft.id("textures/entity/critters/nerite_lines_wide.png"),
            org.overengineer.bettacraft.critters.CritterLooks.Lines.BANDS, BettaCraft.id("textures/entity/critters/apple_bands.png"));

    /** M25 part c: the bands of a bee shrimp (by banding grade), tiger stripes, the dots of the cardinal shrimp. */
    private static final Identifier[] BEE = {BettaCraft.id("textures/entity/critters/shrimp_bee_a.png"),
            BettaCraft.id("textures/entity/critters/shrimp_bee_s.png"), BettaCraft.id("textures/entity/critters/shrimp_bee_ss.png"),
            BettaCraft.id("textures/entity/critters/shrimp_bee_sss.png")};
    private static final Identifier TIGER = BettaCraft.id("textures/entity/critters/shrimp_tiger.png");
    private static final Identifier DOTS = BettaCraft.id("textures/entity/critters/shrimp_dots.png");
    /** M29 part d: the dark marbling of the marbled crayfish. */
    private static final Identifier MARBLE = BettaCraft.id("textures/entity/critters/crayfish_marble.png");

    /** M25 part c: the overlay over the body of a Caridina or a cardinal shrimp and its colour, or null. */
    @Nullable
    static Map.Entry<Identifier, Integer> bodyOverlay(Critter k) {
        if (k.species == CritterSpecies.SULAWESI_SHRIMP) return Map.entry(DOTS, 0xF4F2EE);
        if (k.species == CritterSpecies.FIRE_SHRIMP) return Map.entry(DOTS, 0xF8F4F0); // M48 part b: white dots on deep red
        if (k.species == CritterSpecies.AMANO_SHRIMP) return Map.entry(DOTS, 0x4A3A2E); // M49: the dotted line on grey
        if (k.species == CritterSpecies.MARBLED_CRAYFISH) return Map.entry(MARBLE, 0x3A3424); // M29 part d
        if (k.species != CritterSpecies.CARIDINA) return null;
        int c = k.clientColor;
        if (c == CritterGenes.CARIDINA_RED || c == CritterGenes.CARIDINA_BLACK) return Map.entry(BEE[CritterGenes.banding(k.clientGrade)], 0xF6F4F0);
        if (c == CritterGenes.CARIDINA_TIGER) return Map.entry(TIGER, 0x0C0E1C);
        if (c == CritterGenes.WILD_COLOR) return Map.entry(BEE[0], 0xB4AA98); // the wild bee shrimp: pale bands
        return null; // Taiwan bees: one solid colour
    }

    /** Colour of the soft body of a snail (foot, head, feelers). */
    public static int skinColor(Critter k) {
        return switch (k.species) {
            case ZEBRA_NERITE, HORNED_NERITE, OLIVE_NERITE, RED_NERITE, YELLOW_NERITE -> 0x6E6A60;
            case APPLE_SNAIL -> switch (k.clientColor) {
                case 0, 3 -> 0xD8C8A0; // gold, ivory: pale body
                case 1 -> 0x50607A; // blue
                case 2 -> 0x5A4058; // purple
                default -> 0x4A4038;
            };
            case RAMSHORN -> switch (k.clientColor) {
                case 0 -> 0xE07890; // pink: pink body
                case 1 -> 0x6A7890;
                case 2 -> 0xB0180E; // M21.5: red, a bright red body
                default -> 0x8A2A1C; // the wild red-brown ones have a red body
            };
            case BLADDER_SNAIL -> 0x9A8A70;
            case TURBO_SNAIL -> 0x7A7058;
            case HERMIT_CRAB -> 0x3A6AD0; // the blue legs
            case CLEANER_SHRIMP -> 0xF4F0E8;
            case FIRE_SHRIMP -> 0xF4F0E8;
            case TRUMPET_SNAIL -> 0x8A7A68;
            case ASSASSIN_SNAIL -> 0x6E6A50;
            case TYLOMELANIA -> 0xF0861C; // M25 part c: the orange body of a rabbit snail
            default -> 0x8A8070;
        };
    }

    private static int pale(int c) {
        return CritterGenes.mix(c, 0xF0ECE4, 0.35F);
    }

    private static int argb(int rgb) {
        return 0xFF000000 | (rgb & 0xFFFFFF);
    }

    private static int dead(int rgb) {
        int g = (((rgb >> 16) & 0xFF) + ((rgb >> 8) & 0xFF) + (rgb & 0xFF)) / 3;
        return CritterGenes.mix(rgb, (g << 16) | (g << 8) | g, 0.7F) & 0xFFFFFF | 0;
    }

    // ------------------------------------------------------------------ drawing

    public static void render(TankBlockEntity be, TankData t, float partialTick, PoseStack pose, MultiBufferSource buffers) {
        Level level = be.getLevel();
        if (level == null || (t.critters().isEmpty() && t.critterObjects().isEmpty())) return;
        if (MODELS.isEmpty()) bake();
        BlockPos origin = be.getBlockPos();
        double time = level.getGameTime() + partialTick;
        BlockPos.MutableBlockPos at = new BlockPos.MutableBlockPos();
        for (Critter k : t.critters()) {
            double x = k.renderX(time, TankPlants.SYNC_TICKS), y = k.renderY(time, TankPlants.SYNC_TICKS), z = k.renderZ(time, TankPlants.SYNC_TICKS);
            at.set(Mth.floor(x), Mth.floor(y + 0.05), Mth.floor(z));
            int light = net.minecraft.util.LightCoordsUtil.getLightCoords(level, at);
            pose.pushPose();
            pose.translate(x - origin.getX(), y - origin.getY(), z - origin.getZ());
            orient(pose, k.face, k.renderYaw(time, TankPlants.SYNC_TICKS));
            drawCritter(pose, buffers, k, time, light);
            pose.popPose();
        }
        for (CritterObject o : t.critterObjects()) {
            at.set(Mth.floor(o.x), Mth.floor(o.y), Mth.floor(o.z));
            int light = net.minecraft.util.LightCoordsUtil.getLightCoords(level, at);
            pose.pushPose();
            pose.translate(o.x - origin.getX(), o.y - origin.getY(), o.z - origin.getZ());
            orient(pose, o.face, o.yaw);
            drawObject(pose, buffers, o, light);
            pose.popPose();
        }
    }

    /** Turns the pose so that the model stands on the floor (heading {@code yaw}) or lies with its belly on the glass. */
    private static void orient(PoseStack pose, byte face, float yaw) {
        if (face >= Critter.GLASS_SOUTH && face <= Critter.GLASS_EAST) {
            int dir = face - Critter.GLASS_SOUTH;
            float a = switch (dir) {
                case 0 -> 0F;
                case 1 -> -90F;
                case 2 -> 180F;
                default -> 90F;
            };
            pose.mulPose(Axis.YP.rotationDegrees(a));
            pose.mulPose(Axis.XP.rotationDegrees(-90F));
            pose.mulPose(Axis.YP.rotationDegrees(yaw));
        } else {
            pose.mulPose(Axis.YP.rotationDegrees(-yaw));
        }
    }

    @Nullable
    private static ModelPart group(CritterSpecies.Model m, String name) {
        Map<String, ModelPart> g = GROUPS.get(m);
        return g == null ? null : g.get(name);
    }

    /** M22.3: one animal at the origin of the pose (a wild one in the world), standing on the floor. */
    public static void drawOne(PoseStack pose, MultiBufferSource buffers, Critter k, double time, int light, boolean hurt) {
        if (MODELS.isEmpty()) bake();
        drawCritter(pose, buffers, k, time, light);
    }

    /** M22.3: the texture of a body plan. */
    public static Identifier texture(CritterSpecies.Model m) {
        return BettaCraft.id("textures/entity/critters/" + name(m) + ".png");
    }

    private static void drawCritter(PoseStack pose, MultiBufferSource buffers, Critter k, double time, int light) {
        CritterSpecies.Model m = k.species.model();
        ModelPart root = MODELS.get(m);
        if (root == null) return;
        boolean alive = (k.clientFlags & CritterSync.F_DEAD) == 0;
        boolean berried = (k.clientFlags & CritterSync.F_BERRIED) != 0;
        boolean retract = (k.clientFlags & CritterSync.F_RETRACT) != 0;
        boolean soft = (k.clientFlags & CritterSync.F_SOFT) != 0;
        float size = Math.max(0.3F, k.clientSize);
        float s = (float) (k.species.length() * size);
        if (k.buried) pose.translate(0, -s * 0.45F, 0);
        if (!alive && !k.species.isSnail()) {
            // on its side
            pose.translate(0, s * 0.12F, 0);
            pose.mulPose(Axis.ZP.rotationDegrees(80F));
        }
        pose.scale(s, -s, -s);
        float phase = (float) (time * 0.25 + k.id * 1.37);
        boolean walking = k.moving && alive;
        // animation of the groups
        ModelPart legs = group(m, "legs"), ant = group(m, "antennae"), tent = group(m, "tentacles"), eggs = group(m, "eggs"), horns = group(m, "horns");
        ModelPart foot = group(m, "foot");
        if (legs != null) {
            legs.xRot = walking ? Mth.sin(phase * 2.2F) * 0.18F : Mth.sin(phase * 0.4F) * 0.03F;
            legs.zRot = walking ? Mth.cos(phase * 2.2F) * 0.05F : 0;
        }
        if (ant != null) {
            ant.yRot = Mth.sin(phase * 0.35F) * 0.18F;
            ant.xRot = Mth.cos(phase * 0.27F) * 0.1F;
        }
        if (tent != null) {
            tent.visible = alive && !retract && !k.buried;
            tent.yRot = Mth.sin(phase * 0.2F) * 0.12F;
            tent.xScale = tent.yScale = tent.zScale = 1F;
        }
        if (foot != null) foot.visible = alive && !k.buried;
        if (eggs != null) eggs.visible = berried && alive;
        if (horns != null) horns.visible = k.species == CritterSpecies.HORNED_NERITE;
        // tints
        var lk = look(k);
        int body = lk.body();
        if (soft) body = CritterGenes.mix(body, 0xF4ECE0, 0.45F);
        if (!alive) body = dead(body);
        int skin = alive ? skinColor(k) : dead(skinColor(k));
        VertexConsumer vc = buffers.getBuffer(RenderTypes.entityCutout(TEXTURES.get(m)));
        int ov = OverlayTexture.NO_OVERLAY;
        for (Map.Entry<String, ModelPart> e : GROUPS.get(m).entrySet()) {
            ModelPart p = e.getValue();
            if (!p.visible) continue;
            int tint = switch (e.getKey()) {
                case "shell" -> k.species == CritterSpecies.HERMIT_CRAB ? (alive ? 0x8A6E52 : dead(0x8A6E52)) : body; // M20: the borrowed shell
                case "body", "claws" -> body;
                case "legs", "antennae" -> alive ? pale(body) : dead(pale(body));
                case "eyes" -> k.species == CritterSpecies.CARIDINA && k.clientColor == CritterGenes.CARIDINA_TIGER ? 0xF07A18 : EYE; // M25c: orange eyes
                case "eggs" -> k.species.isCrayfish() ? 0x3A2620 : CritterGenes.mix(0xE8C440, body, 0.25F);
                case "foot", "tentacles" -> skin;
                case "horns" -> 0x2A2420;
                default -> body;
            };
            p.render(pose, vc, light, ov, argb(tint));
        }
        // M25 part c: bands, stripes or dots over the body of a shrimp
        var bo = bodyOverlay(k);
        ModelPart bodyPart = group(m, "body");
        if (bo != null && bodyPart != null && bodyPart.visible) {
            int oc = soft ? CritterGenes.mix(bo.getValue(), 0xF4ECE0, 0.45F) : bo.getValue();
            bodyPart.render(pose, buffers.getBuffer(RenderTypes.entityCutout(bo.getKey())), light, ov, argb(alive ? oc : dead(oc)));
        }
        // M21.5: lines or bands over the shell (same model part, an overlay texture with its own colour)
        if (lk.kind() != org.overengineer.bettacraft.critters.CritterLooks.Lines.NONE) {
            ModelPart shell = group(m, "shell");
            if (shell != null && shell.visible) {
                int lc = alive ? lk.lines() : dead(lk.lines());
                shell.render(pose, buffers.getBuffer(RenderTypes.entityCutout(LINES.get(lk.kind()))), light, ov, argb(lc));
            }
        }
    }

    private static void drawObject(PoseStack pose, MultiBufferSource buffers, CritterObject o, int light) {
        VertexConsumer vc;
        if (o.kind == CritterObject.Kind.CLUTCH) {
            // a pink cluster of eggs on the glass: the egg group of the shrimp model, much larger
            ModelPart eggs = group(CritterSpecies.Model.SHRIMP, "eggs");
            if (eggs == null) return;
            // about 0.1 blocks wide and 0.12 high on the glass, 0.06 thick
            pose.translate(0, -0.06F, 0); // the egg group floats above its origin in the model: down onto the glass
            pose.scale(0.72F, -0.85F, -0.65F);
            vc = buffers.getBuffer(RenderTypes.entityCutout(TEXTURES.get(CritterSpecies.Model.SHRIMP)));
            boolean was = eggs.visible;
            eggs.visible = true;
            eggs.render(pose, vc, light, OverlayTexture.NO_OVERLAY, argb(0xF07AA8));
            eggs.visible = was;
            return;
        }
        if (o.kind == CritterObject.Kind.LARVAE) {
            // M49: a faint cloud of Amano larvae: tiny pale specks in the water
            ModelPart eggs = group(CritterSpecies.Model.SHRIMP, "eggs");
            if (eggs == null) return;
            vc = buffers.getBuffer(RenderTypes.entityCutout(TEXTURES.get(CritterSpecies.Model.SHRIMP)));
            boolean was = eggs.visible;
            eggs.visible = true;
            float t = (net.minecraft.util.Util.getMillis() % 100000L) / 1000F + o.yaw;
            for (int i = 0; i < 9; i++) {
                pose.pushPose();
                float a = i * 2.39F + t * 0.3F;
                pose.translate(net.minecraft.util.Mth.cos(a) * (0.03F + i * 0.012F), net.minecraft.util.Mth.sin(t * 0.7F + i) * 0.03F + (i % 3) * 0.03F,
                        net.minecraft.util.Mth.sin(a) * (0.03F + i * 0.012F));
                pose.scale(0.26F, -0.26F, -0.26F);
                eggs.render(pose, vc, light, OverlayTexture.NO_OVERLAY, argb(0xE8ECE0));
                pose.popPose();
            }
            eggs.visible = was;
            return;
        }
        if (o.kind == CritterObject.Kind.AXOLOTL_EGGS) {
            // M29 part d: axolotl eggs on a plant: a few small, pale, jelly-coated eggs (the egg group of the shrimp model)
            ModelPart eggs = group(CritterSpecies.Model.SHRIMP, "eggs");
            if (eggs == null) return;
            vc = buffers.getBuffer(RenderTypes.entityCutout(TEXTURES.get(CritterSpecies.Model.SHRIMP)));
            boolean was = eggs.visible;
            eggs.visible = true;
            for (int i = 0; i < 5; i++) {
                pose.pushPose();
                pose.translate((i - 2) * 0.045F, (i % 2) * 0.05F - 0.04F + (i == 2 ? 0.07F : 0), (i % 3 - 1) * 0.03F);
                pose.mulPose(com.mojang.math.Axis.YP.rotationDegrees(i * 70F));
                pose.scale(0.8F, -0.85F, -0.7F);
                eggs.render(pose, vc, light, OverlayTexture.NO_OVERLAY, argb(i % 2 == 1 ? 0xF6F2E2 : 0xE4DEC4));
                pose.popPose();
            }
            eggs.visible = was;
            return;
        }
        // a shed crayfish shell: the body, pale and empty
        CritterSpecies.Model m = o.species.model();
        ModelPart bodyPart = group(m, "body");
        if (bodyPart == null) return;
        float s = (float) (o.species.length() * Math.max(0.3F, o.size));
        pose.scale(s, -s, -s);
        vc = buffers.getBuffer(RenderTypes.entityCutout(TEXTURES.get(m)));
        bodyPart.render(pose, vc, light, OverlayTexture.NO_OVERLAY, argb(0xE8E0D2));
        ModelPart claws = group(m, "claws");
        if (claws != null) claws.render(pose, vc, light, OverlayTexture.NO_OVERLAY, argb(0xE0D8CA));
    }
}
