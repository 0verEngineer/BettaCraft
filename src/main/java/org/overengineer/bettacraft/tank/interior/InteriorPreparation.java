package org.overengineer.bettacraft.tank.interior;

import it.unimi.dsi.fastutil.ints.Int2ObjectLinkedOpenHashMap;
import it.unimi.dsi.fastutil.longs.LongArrayList;
import it.unimi.dsi.fastutil.longs.LongOpenHashSet;
import it.unimi.dsi.fastutil.longs.LongSet;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;
import java.util.UUID;
import net.minecraft.network.chat.Component;
import net.minecraft.server.MinecraftServer;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.server.level.TicketType;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.chunk.LevelChunk;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Builds interior regions without stalling the server (M3 performance pass). Measured in M0, building the shell of a
 * 16^3 tank at scale 16 synchronously took 1.3 s (10 s in fresh grid cells), almost all of it generating the 324
 * chunks on the server thread. Here the chunks are requested with tickets and generated by the world-gen workers;
 * once they are loaded the shell is written chunk by chunk within a time budget per tick, then waiting players are
 * teleported in.
 */
public final class InteriorPreparation {
    private static final Logger LOGGER = LoggerFactory.getLogger("bettacraft/interior");
    public static final TicketType<ChunkPos> TICKET = TicketType.create("bettacraft_interior", Comparator.comparingLong(ChunkPos::toLong), 300);
    /** Main-thread budget per tick for writing shell chunks. */
    private static final long BUDGET_NANOS = 8_000_000L;

    private static final class Job {
        final InteriorRegion region;
        final Set<UUID> players = new LinkedHashSet<>();
        final LongArrayList chunks = new LongArrayList();
        final LongSet touched = new LongOpenHashSet();
        int nextChunk;
        boolean ticketsAdded;
        final long startNanos = System.nanoTime();
        long mainThreadNanos;
        int ticks;

        Job(InteriorRegion region) {
            this.region = region;
            int[] c = InteriorManager.shellChunks(region);
            for (int cx = c[0]; cx <= c[1]; cx++)
                for (int cz = c[2]; cz <= c[3]; cz++) chunks.add(ChunkPos.asLong(cx, cz));
        }
    }

    private static final Int2ObjectLinkedOpenHashMap<Job> JOBS = new Int2ObjectLinkedOpenHashMap<>();
    /** Stats of the last finished job (bench). */
    public static volatile String lastStats = "";

    private InteriorPreparation() {}

    public static boolean isPreparing(int regionId) {
        return JOBS.containsKey(regionId);
    }

    /** Starts (or joins) the preparation of a region; {@code player} (may be null) is teleported in when it is ready. */
    public static void prepare(MinecraftServer server, InteriorRegion region, @javax.annotation.Nullable ServerPlayer player) {
        Job job = JOBS.computeIfAbsent(region.id(), k -> new Job(region));
        if (player != null) {
            job.players.add(player.getUUID());
            player.displayClientMessage(Component.translatable("message.bettacraft.interior.preparing"), true);
        }
    }

    static void cancel(int regionId) {
        Job j = JOBS.remove(regionId);
        if (j != null) LOGGER.debug("Cancelled preparation of region {}", regionId);
    }

    public static void clearAll() {
        JOBS.clear();
    }

    /** Server tick: advance the jobs. */
    public static void tick(MinecraftServer server) {
        if (JOBS.isEmpty()) return;
        ServerLevel level = InteriorManager.interiorLevel(server);
        if (level == null) {
            JOBS.clear();
            return;
        }
        long tickStart = System.nanoTime();
        List<Integer> done = new ArrayList<>();
        for (Job job : JOBS.values()) {
            job.ticks++;
            if (InteriorRegions.get(server).get(job.region.id()) != job.region || job.region.built()) {
                done.add(job.region.id());
                if (job.region.built()) teleport(server, job);
                continue;
            }
            long t0 = System.nanoTime();
            if (!job.ticketsAdded) {
                for (long c : job.chunks) level.getChunkSource().addRegionTicket(TICKET, new ChunkPos(c), 0, new ChunkPos(c));
                job.ticketsAdded = true;
            }
            boolean finished = true;
            while (job.nextChunk < job.chunks.size()) {
                if (System.nanoTime() - tickStart > BUDGET_NANOS) {
                    finished = false;
                    break;
                }
                long c = job.chunks.getLong(job.nextChunk);
                LevelChunk chunk = level.getChunkSource().getChunkNow(ChunkPos.getX(c), ChunkPos.getZ(c));
                if (chunk == null) {
                    finished = false; // still generating on the workers
                    break;
                }
                InteriorManager.buildShellChunk(level, job.region, ChunkPos.getX(c), ChunkPos.getZ(c), job.touched);
                job.nextChunk++;
            }
            job.mainThreadNanos += System.nanoTime() - t0;
            if (finished) {
                double wall = (System.nanoTime() - job.startNanos) / 1e6;
                InteriorManager.finishShell(server, level, job.region, job.touched, job.mainThreadNanos / 1e6, "async over " + job.ticks + " ticks, "
                        + String.format(java.util.Locale.ROOT, "%.0f ms wall", wall));
                lastStats = String.format(java.util.Locale.ROOT, "%dx%dx%d: %.0f ms wall time, %.1f ms on the server thread over %d ticks, %d chunks",
                        job.region.sizeX(), job.region.sizeY(), job.region.sizeZ(), wall, job.mainThreadNanos / 1e6, job.ticks, job.chunks.size());
                done.add(job.region.id());
                teleport(server, job);
            } else if (job.ticks % 20 == 0) {
                int pct = job.nextChunk * 100 / Math.max(1, job.chunks.size());
                for (UUID u : job.players) {
                    ServerPlayer p = server.getPlayerList().getPlayer(u);
                    if (p != null) p.displayClientMessage(Component.translatable("message.bettacraft.interior.preparing_progress", pct), true);
                }
            }
        }
        for (int id : done) JOBS.remove(id);
    }

    private static void teleport(MinecraftServer server, Job job) {
        for (UUID u : job.players) {
            ServerPlayer p = server.getPlayerList().getPlayer(u);
            if (p != null && p.isAlive() && !InteriorManager.isInterior(p.level())) InteriorManager.teleportInto(p, job.region);
        }
    }
}
